"""
fuzzy.py — мягкое исправление опечаток во входной фразе (уровень 2+).

Для каждой леммы, которой нет среди ключевых слов, подбирается ближайшее
ключевое слово по мере схожести строк (difflib). Если найдено достаточно
близкое (выше порога) — лемма заменяется на него. Это позволяет распознать
запросы с опечатками: «общжитие» → «общежитие», «стоимост» → «стоимость».

Порог и минимальная длина подобраны консервативно, чтобы не подменять
короткие и непохожие слова. Стандартная библиотека, внешних зависимостей
не требуется.
"""

import difflib


def correct_lemmas(lemmas, vocab, cutoff=0.82, min_len=4):
    """
    Заменяет леммы-опечатки на ближайшие ключевые слова из словаря.

    :param lemmas: множество лемм входной фразы
    :param vocab: множество известных ключевых слов (леммы категорий)
    :param cutoff: порог схожести от 0 до 1 (чем выше, тем строже)
    :param min_len: слова короче этой длины не исправляются
    :return: новое множество лемм с исправленными опечатками
    """
    vocab_list = list(vocab)
    corrected = set()
    for word in lemmas:
        # Слово уже известно или слишком короткое — оставляем как есть.
        if word in vocab or len(word) < min_len:
            corrected.add(word)
            continue
        match = difflib.get_close_matches(word, vocab_list, n=1, cutoff=cutoff)
        corrected.add(match[0] if match else word)
    return corrected
