"""
preprocess2.py — предобработка входной фразы для уровня 2.

Отличия от предобработки уровня 1:
  - лемматизация выполняется средствами spaCy (с учётом контекста),
    при отсутствии spaCy — через pymorphy3 (см. nlp_spacy.py);
  - после лемматизации применяется словарь синонимов: разговорные и
    сокращённые формы заменяются на канонические ключевые слова.

Стоп-слова отсекаются по списку NLTK (как и на уровне 1), с запасным
встроенным списком.
"""

import json
import os

from chatbot.nlp_spacy import lemmatize


_BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_SYN_PATH = os.path.join(_BASE_DIR, "synonyms.json")


# Стоп-слова: NLTK, иначе встроенный запасной список.
try:
    from nltk.corpus import stopwords
    _STOPWORDS = set(stopwords.words("russian"))
except Exception:
    _STOPWORDS = {
        "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как",
        "а", "то", "все", "она", "так", "его", "но", "да", "ты", "к", "у",
        "же", "вы", "за", "бы", "по", "только", "ее", "мне", "было", "вот",
        "от", "меня", "о", "из", "ему", "теперь", "даже", "ну", "ли", "если",
        "или", "ни", "быть", "был", "него", "до", "вас", "уж", "вам", "ведь",
        "там", "потом", "себя", "ничего", "ей", "они", "тут", "есть", "надо",
        "ней", "для", "мы", "тебя", "их", "чем", "была", "сам", "чтоб", "без",
        "чего", "раз", "тоже", "себе", "под", "будет", "ж", "тогда", "кто",
        "этот", "того", "потому", "этого", "совсем", "ним", "здесь", "этом",
        "мой", "тем", "чтобы", "нее", "были", "куда", "всех", "можно", "при",
        "два", "об", "другой", "хоть", "после", "над", "больше", "тот",
        "через", "эти", "нас", "про", "всего", "них", "много", "разве", "эту",
        "моя", "свою", "этой", "перед", "лучше", "чуть", "том", "такой", "им",
        "более", "всегда", "конечно", "всю", "между",
    }


def _load_synonyms():
    if not os.path.exists(_SYN_PATH):
        return {}
    with open(_SYN_PATH, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("synonyms", {})


_SYNONYMS = _load_synonyms()


def preprocess2(text):
    """
    Превращает фразу в множество лемм с подстановкой синонимов.

    :param text: строка пользователя
    :return: set лемм (значимые слова, синонимы заменены на канонические)
    """
    result = set()
    for lemma in lemmatize(text):
        if lemma in _STOPWORDS:
            continue
        # Замена синонима на каноническую форму, если она задана.
        lemma = _SYNONYMS.get(lemma, lemma)
        if lemma in _STOPWORDS:
            continue
        result.add(lemma)
    return result
