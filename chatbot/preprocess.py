"""
preprocess.py — предобработка входной фразы пользователя.

Этапы обработки:
  1. перевод в нижний регистр;
  2. разбиение на слова (токенизация);
  3. удаление стоп-слов (предлоги, союзы, частицы);
  4. приведение каждого слова к начальной форме (лемме) через pymorphy3.

Результат — множество лемм, по которому дальше идёт сопоставление
с ключевыми словами категорий.
"""

import re

import pymorphy3


# Морфологический анализатор создаётся один раз при импорте модуля —
# его инициализация довольно тяжёлая, повторять на каждое слово нельзя.
_morph = pymorphy3.MorphAnalyzer()

# Регулярное выражение для токенизации: берём последовательности
# русских и латинских букв и цифр. Знаки препинания отсекаются.
_TOKEN_RE = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)

# Список русских стоп-слов. Пытаемся взять из NLTK; если данные не
# загружены, используем встроенный запасной список, чтобы модуль
# работал в любом случае.
try:
    from nltk.corpus import stopwords
    _STOPWORDS = set(stopwords.words("russian"))
except Exception:
    _STOPWORDS = {
        "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как",
        "а", "то", "все", "она", "так", "его", "но", "да", "ты", "к",
        "у", "же", "вы", "за", "бы", "по", "только", "ее", "мне", "было",
        "вот", "от", "меня", "о", "из", "ему", "теперь", "даже", "ну",
        "ли", "если", "или", "ни", "быть", "был", "него", "до", "вас",
        "нибудь", "уж", "вам", "ведь", "там", "потом", "себя", "ничего",
        "ей", "они", "тут", "где", "есть", "надо", "ней", "для", "мы",
        "тебя", "их", "чем", "была", "сам", "чтоб", "без", "будто", "чего",
        "раз", "тоже", "себе", "под", "будет", "ж", "тогда", "кто", "этот",
        "того", "потому", "этого", "какой", "совсем", "ним", "здесь", "этом",
        "один", "почти", "мой", "тем", "чтобы", "нее", "были", "куда", "зачем",
        "всех", "никогда", "можно", "при", "наконец", "два", "об", "другой",
        "хоть", "после", "над", "больше", "тот", "через", "эти", "нас", "про",
        "всего", "них", "какая", "много", "разве", "три", "эту", "моя", "впрочем",
        "хорошо", "свою", "этой", "перед", "иногда", "лучше", "чуть", "том",
        "нельзя", "такой", "им", "более", "всегда", "конечно", "всю", "между",
    }


def preprocess(text):
    """
    Превращает фразу пользователя в множество лемм.

    :param text: строка, введённая пользователем
    :return: set строк (леммы значимых слов фразы)
    """
    text = text.lower()
    tokens = _TOKEN_RE.findall(text)

    lemmas = set()
    for token in tokens:
        if token in _STOPWORDS:
            continue
        # Латинские слова и цифры pymorphy3 не разбирает —
        # оставляем их как есть (нужно для it, mba, egэ и т. п.).
        if re.fullmatch(r"[a-z0-9]+", token):
            lemmas.add(token)
            continue
        lemma = _morph.parse(token)[0].normal_form
        if lemma not in _STOPWORDS:
            lemmas.add(lemma)

    return lemmas
