"""
check_vectors.py — проверка векторной ветки уровня 3 на модели spaCy
с векторами (ru_core_news_lg или ru_core_news_md).

Запуск (в активированном окружении, из корня проекта):
    python check_vectors.py

Скрипт сообщает, какая модель загружена, есть ли у неё векторы, и
прогоняет несколько перефразировок БЕЗ общих слов с ключевыми словами
категорий. Для каждой фразы выводится категория и мера сходства по двум
методам: векторному и TF-IDF. На таких фразах ожидается, что векторный
метод распознаёт смысл, а TF-IDF — нет (у фраз нет общих слов).

Вывод этого скрипта удобно приложить к отчёту (раздел тестирования).
"""

from chatbot.knowledge import load_knowledge
from chatbot.nlp_spacy import get_engine_info
from chatbot.semantic import VectorBackend, TfidfBackend


def main():
    info = get_engine_info()
    print("Движок NLP:", info)
    if not info.get("has_vectors"):
        print(
            "\nВНИМАНИЕ: у текущей модели нет векторов. Векторная ветка\n"
            "работать не будет. Нужна модель ru_core_news_lg или md.\n"
            "Проверьте: python -m spacy download ru_core_news_lg"
        )
        return

    kb = load_knowledge("academic")
    vec = VectorBackend(kb)
    tf = TfidfBackend(kb)

    # Перефразировки без общих слов с ключевыми словами категорий.
    phrases = [
        "куда селят приезжих студентов",        # ожидается общежитие
        "во что встанет год учёбы",             # ожидается стоимость
        "берёте ли вы людей из других стран",   # ожидается иностранным
        "можно грызть гранит науки из дома",     # ожидается дистанционное
        "реально ли вообще не платить",          # ожидается бюджет
    ]

    print("\n%-38s | %-22s | %-22s" % ("Фраза", "Вектор", "TF-IDF"))
    print("-" * 88)
    for p in phrases:
        vc, vs = vec.match(p)
        tc, ts = tf.match(p)
        vstr = f"{vc} ({vs:.2f})" if vc else "— (0.00)"
        tstr = f"{tc} ({ts:.2f})" if tc else "— (0.00)"
        print("%-38s | %-22s | %-22s" % (p, vstr, tstr))

    print(
        "\nЕсли в столбце «Вектор» осмысленные категории, а в «TF-IDF» —\n"
        "прочерки или нерелевантное, значит векторное сходство работает\n"
        "и понимает перефразировки, недоступные лексическому методу."
    )


if __name__ == "__main__":
    main()
